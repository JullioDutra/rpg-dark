const SEM_ACENTO = { Ō: "O", ō: "O", Ū: "U", ū: "U", Ā: "A", ā: "A", Ç: "C", Ã: "A", Õ: "O", É: "E", Ê: "E", Í: "I", Ó: "O", Ú: "U", Á: "A", Â: "A" };

export function largura(texto) {
  return [...texto].length * 4 - 1;
}

// Escreve texto com sombra/contorno para legibilidade sobre o mapa
export function escrever(t, texto, x, y, cor = "#ffffff", contorno = "#1a1024") {
  const chars = [...texto.toUpperCase()].map((c) => SEM_ACENTO[c] ?? c);
  const pontos = [];
  chars.forEach((c, i) => {
    const g = G[c] ?? G[" "];
    g.forEach((linha, dy) => [...linha].forEach((b, dx) => { if (b === "1") pontos.push([x + i * 4 + dx, y + dy]); }));
  });
  if (contorno) for (const [px, py] of pontos) for (const [ox, oy] of [[1, 0], [-1, 0], [0, 1], [0, -1], [1, 1]]) t.set(px + ox, py + oy, contorno);
  for (const [px, py] of pontos) t.set(px, py, cor);
}
